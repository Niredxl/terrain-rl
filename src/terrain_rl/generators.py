"""Procedural, GAN-style, and diffusion terrain generators.

The neural generators intentionally contain inference architectures only. They do
not include training data loaders, optimizers, or training loops.
"""

from __future__ import annotations

import math
from typing import Literal

import numpy as np
import torch
from torch import Tensor, nn
from torch.nn import functional as F

from .terrain import HeightmapTerrain, TerrainOutput


class PerlinTerrainGenerator(HeightmapTerrain):
    """Small multi-octave value-noise approximation suitable for fast resets."""

    def __init__(self, resolution: int = 64, size: float = 10.0, seed: int | None = None, octaves: int = 4) -> None:
        super().__init__(resolution, size, seed)
        self.octaves = octaves

    def generate(self, seed: int | None = None) -> TerrainOutput:
        rng = self._rng(seed)
        y, x = np.mgrid[0 : self.resolution, 0 : self.resolution]
        result = np.zeros_like(x, dtype=np.float32)
        amplitude, total = 1.0, 0.0
        for octave in range(self.octaves):
            grid = max(2, 2 ** (octave + 2))
            coarse = rng.random((grid + 1, grid + 1), dtype=np.float32)
            gx = np.linspace(0, grid, self.resolution, endpoint=False)
            gy = np.linspace(0, grid, self.resolution, endpoint=False)
            ix, iy = gx.astype(int), gy.astype(int)
            fx, fy = gx - ix, gy - iy
            ix1, iy1 = np.minimum(ix + 1, grid), np.minimum(iy + 1, grid)
            wx = fx * fx * (3 - 2 * fx)
            wy = fy * fy * (3 - 2 * fy)
            values = np.empty_like(result)
            for row, (j, j1, wy_value) in enumerate(zip(iy, iy1, wy)):
                a = coarse[j, ix] * (1 - wx) + coarse[j, ix1] * wx
                b = coarse[j1, ix] * (1 - wx) + coarse[j1, ix1] * wx
                values[row] = a * (1 - wy_value) + b * wy_value
            result += amplitude * values
            total += amplitude
            amplitude *= 0.5
        return self._derived_maps((result / total - 0.5) * 2.0)


class CellularAutomataTerrainGenerator(HeightmapTerrain):
    """Cave-like terrain generated by smoothing a random binary field."""

    def __init__(self, resolution: int = 64, size: float = 10.0, seed: int | None = None, iterations: int = 5) -> None:
        super().__init__(resolution, size, seed)
        self.iterations = iterations

    def generate(self, seed: int | None = None) -> TerrainOutput:
        rng = self._rng(seed)
        field = (rng.random((self.resolution, self.resolution)) > 0.52).astype(np.float32)
        for _ in range(self.iterations):
            padded = np.pad(field, 1, mode="edge")
            neighbors = sum(
                padded[dy : dy + self.resolution, dx : dx + self.resolution]
                for dy in range(3)
                for dx in range(3)
                if (dy, dx) != (1, 1)
            )
            field = (neighbors >= 4).astype(np.float32)
        return self._derived_maps(field * 2.0 - 1.0)


class _TerrainGenerator(nn.Module):
    """GAN decoder: latent vector -> three heightfield-related channels."""

    def __init__(self, latent_dim: int, resolution: int) -> None:
        super().__init__()
        self.resolution = resolution
        self.fc = nn.Linear(latent_dim, 64 * 4 * 4)
        self.blocks = nn.Sequential(
            nn.Conv2d(64, 32, 3, padding=1),
            nn.LeakyReLU(0.2, inplace=True),
            nn.Conv2d(32, 16, 3, padding=1),
            nn.LeakyReLU(0.2, inplace=True),
            nn.Conv2d(16, 3, 1),
        )

    def forward(self, latent: Tensor) -> Tensor:
        x = self.fc(latent).view(-1, 64, 4, 4)
        # Resize the learned feature map to the requested heightfield resolution.
        x = F.interpolate(x, size=(self.resolution, self.resolution), mode="bilinear", align_corners=False)
        return torch.tanh(self.blocks(x))


class GANTerrainGenerator(HeightmapTerrain):
    """Inference-only lightweight GAN-style terrain decoder."""

    def __init__(
        self,
        resolution: int = 64,
        size: float = 10.0,
        seed: int | None = None,
        latent_dim: int = 64,
        device: str | torch.device = "cpu",
    ) -> None:
        super().__init__(resolution, size, seed)
        self.latent_dim = latent_dim
        self.device = torch.device(device)
        self.generator = _TerrainGenerator(latent_dim, resolution).to(self.device).eval()

    def generate(self, seed: int | None = None) -> TerrainOutput:
        rng = self._rng(seed)
        latent = torch.from_numpy(rng.standard_normal((1, self.latent_dim), dtype=np.float32)).to(self.device)
        with torch.inference_mode():
            maps = self.generator(latent)[0]
        elevation = self.as_numpy(maps[0])
        return self._derived_maps(elevation)


class _DiffusionUNet(nn.Module):
    """Minimal noise predictor with a timestep conditioning channel."""

    def __init__(self, channels: int = 32) -> None:
        super().__init__()
        self.time = nn.Sequential(nn.Linear(32, channels), nn.SiLU(), nn.Linear(channels, channels))
        self.down = nn.Conv2d(2, channels, 3, padding=1)
        self.mid = nn.Sequential(nn.SiLU(), nn.Conv2d(channels, channels, 3, padding=1), nn.SiLU())
        self.up = nn.Conv2d(channels, 1, 3, padding=1)

    def forward(self, x: Tensor, timestep: Tensor) -> Tensor:
        embedding = _timestep_embedding(timestep, 32)
        h = self.down(torch.cat([x, x.new_zeros(x.shape)], dim=1))
        h = h + self.time(embedding)[:, :, None, None]
        return self.up(self.mid(h))


def _timestep_embedding(timestep: Tensor, dimension: int) -> Tensor:
    half = dimension // 2
    frequencies = torch.exp(-math.log(10000) * torch.arange(half, device=timestep.device) / max(half - 1, 1))
    angles = timestep[:, None].float() * frequencies[None]
    return torch.cat([angles.sin(), angles.cos()], dim=1)


class DiffusionTerrainGenerator(HeightmapTerrain):
    """Minimal inference-only DDPM sampler backed by a compact noise predictor."""

    def __init__(
        self,
        resolution: int = 64,
        size: float = 10.0,
        seed: int | None = None,
        diffusion_steps: int = 8,
        device: str | torch.device = "cpu",
    ) -> None:
        super().__init__(resolution, size, seed)
        self.diffusion_steps = diffusion_steps
        self.device = torch.device(device)
        self.unet = _DiffusionUNet().to(self.device).eval()
        self.registered_betas = torch.linspace(1e-4, 0.02, diffusion_steps, device=self.device)

    def generate(self, seed: int | None = None) -> TerrainOutput:
        generator = torch.Generator(device=self.device)
        generator.manual_seed(int(self._rng(seed).integers(0, 2**31 - 1)))
        x = torch.randn((1, 1, self.resolution, self.resolution), generator=generator, device=self.device)
        with torch.inference_mode():
            for index in range(self.diffusion_steps - 1, -1, -1):
                t = torch.full((1,), index, device=self.device, dtype=torch.long)
                beta = self.registered_betas[index]
                alpha = 1 - beta
                prediction = self.unet(x, t)
                x = (x - beta / torch.sqrt(1 - torch.cumprod(1 - self.registered_betas, 0)[index]) * prediction) / torch.sqrt(alpha)
                if index:
                    noise = torch.randn(x.shape, generator=generator, device=self.device)
                    x = x + torch.sqrt(beta) * noise
        elevation = self.as_numpy(x[0, 0].clamp(-1, 1))
        return self._derived_maps(elevation)
